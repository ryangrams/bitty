inline int textWidth(const char* text, int scale = 1, int maxChars = 99) {
  if (scale < 1 || maxChars < 1) return 0;
  int count = 0;
  while (text && text[count] && count < maxChars) ++count;
  return count * Advance * scale;
}

// The caller owns width*height pixels. Scaling repeats complete bitmap pixels.
inline void draw(uint16_t* output, int width, int height, const char* text,
                 int x, int y, uint16_t color, int scale = 1, int maxChars = 99) {
  if (!output || width < 1 || height < 1 || (scale != 1 && scale != 2)) return;
  for (int i = 0; text && text[i] && i < maxChars; ++i) {
    const uint8_t* rows = glyph(text[i]);
    for (int row = 0; row < Height; ++row) {
      for (int col = 0; col < Width; ++col) {
        if (!(rows[row] & (1u << (Width - 1 - col)))) continue;
        for (int dy = 0; dy < scale; ++dy) {
          const int py = y + row * scale + dy;
          if (py < 0 || py >= height) continue;
          for (int dx = 0; dx < scale; ++dx) {
            const int px = x + col * scale + dx;
            if (px >= 0 && px < width) output[py * width + px] = color;
          }
        }
      }
    }
    x += Advance * scale;
  }
}

